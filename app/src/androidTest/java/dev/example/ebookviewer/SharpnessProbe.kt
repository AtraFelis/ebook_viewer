package dev.example.ebookviewer

import android.os.Bundle
import android.os.Debug
import android.os.ParcelFileDescriptor
import android.os.SystemClock
import android.view.MotionEvent
import java.io.File
import java.security.MessageDigest
import java.util.concurrent.atomic.AtomicInteger
import kotlin.math.ceil
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/** Actual View/worker, synthetic files only. onDraw timing is not physical screen presentation. */
class SharpnessProbe {
    private val instrumentation get() = PdfRendererDeviceTest.instrumentation as P0Instrumentation
    private val ui get() = DeviceGestures(instrumentation)

    private data class Progress(
        val revision: Long,
        val changed: Long,
        val first: Long?,
        val sharp: Long?,
        val fraction: Double
    )

    @Test
    fun normalScrollBaseline() {
        val runs = JSONArray()
        val report = JSONObject().put("kind", "synthetic normal scroll; onDraw submission")
            .put("runs", runs).put("samplesPerScenario", 30)
        try {
            for (fixture in listOf("vector", "gray.pdf", "rgb.pdf")) {
                val file = fixture(fixture)
                val sha = MessageDigest.getInstance("SHA-256").digest(file.readBytes())
                    .joinToString("") { "%02x".format(it) }
                repeat(instrumentation.probeRuns) { run ->
                    runs.put(run(fixture, file, sha, run + 1))
                }
            }
        } finally {
            instrumentation.sendStatus(
                2,
                Bundle().apply { putString("sharpnessReport", report.toString()) }
            )
        }
    }

    private fun fixture(name: String): File {
        // Keep generated bytes across APK updates so before/after vector SHA also matches.
        val file = File(instrumentation.targetContext.cacheDir, "sharpness-v1-$name.pdf")
        if (name == "vector") {
            if (!file.exists()) SyntheticDocument.write(file)
        } else {
            instrumentation.context.assets.open(name).use { input ->
                file.outputStream().use { output -> input.copyTo(output) }
            }
        }
        assertTrue("Synthetic input exceeded 4 MiB", file.length() in 1..4L * 1024 * 1024)
        return file
    }

    private fun run(name: String, file: File, sha: String, run: Int): JSONObject {
        val activity = ui.launch()
        lateinit var view: PdfCanvasView
        lateinit var worker: PdfWorker
        var initialized = false
        var progress: Progress? = null
        var maxCache = 0
        val delivered = ArrayList<TileTiming>()
        val failure = AtomicInteger()
        var pages = 0
        var initialZoom = 0.0
        var viewportWidth = 0
        var viewportHeight = 0
        var refreshHz = 0f
        val fdBefore = File("/proc/self/fd").list()?.size ?: -1
        val memoryBefore = memory()
        val scenarios = JSONArray()
        try {
            ui.onMain {
                view = PdfCanvasView(activity) { worker.request(it) }
                worker = PdfWorker(
                    onLoaded = { sizes ->
                        pages = sizes.size
                        view.setPages(sizes)
                    },
                    onTile = { tile, bitmap -> view.putTile(tile, bitmap) },
                    onError = { failure.incrementAndGet() },
                    onTiming = { delivered.add(it) }
                )
                initialized = true
                activity.setContentView(view)
                view.onSharpnessDraw = { draw ->
                    val previous = progress?.takeIf { it.revision == draw.revision }
                    progress = Progress(
                        draw.revision,
                        draw.changedNanos,
                        previous?.first ?: draw.drawnNanos.takeIf { draw.sharpArea > 0.0 },
                        previous?.sharp ?: draw.drawnNanos.takeIf { draw.sharpFraction >= 0.95 },
                        draw.sharpFraction
                    )
                    maxCache = maxOf(maxCache, draw.cachedBytes)
                }
                worker.open { ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_ONLY) }
            }
            ui.await("Synthetic catalog did not finish", 30_000) {
                failure.get() == 0 && pages == if (name == "vector") 100 else 48
            }
            ui.await("Initial view not sharp") { progress?.sharp != null }
            ui.onMain {
                initialZoom = requireNotNull(view.readingPosition()).zoom
                viewportWidth = view.width
                viewportHeight = view.height
                @Suppress("DEPRECATION")
                refreshHz = activity.windowManager.defaultDisplay.refreshRate
            }
            for (forward in listOf(true, false)) {
                val samples = JSONArray()
                repeat(30) {
                    val previousRevision = ui.onMain { progress?.revision }
                    drag(view, forward)
                    val limit = SystemClock.elapsedRealtimeNanos() + 2_000_000_000L
                    var sample: Progress?
                    do {
                        sample = ui.onMain { progress }
                        if (sample?.revision != previousRevision && sample?.sharp != null) break
                        SystemClock.sleep(10)
                    } while (SystemClock.elapsedRealtimeNanos() < limit)
                    val current = requireNotNull(sample)
                    assertTrue(
                        "Gesture did not change viewport",
                        current.revision != previousRevision
                    )
                    val latency = current.sharp?.let { (it - current.changed) / 1_000_000.0 }
                    samples.put(
                        JSONObject().put(
                            "firstSharpMs",
                            current.first?.let { (it - current.changed) / 1_000_000.0 }
                                ?: JSONObject.NULL
                        ).put("sharp95Ms", latency ?: JSONObject.NULL)
                            .put("timeout", latency == null || latency > 2000.0)
                            .put("lastSharpFraction", current.fraction)
                    )
                }
                scenarios.put(
                    JSONObject().put(
                        "direction",
                        if (forward) "first-forward" else "reverse-revisit"
                    )
                        .put("samples", samples)
                )
            }
            assertEquals("Render error", 0, failure.get())
            assertTrue("Cache exceeded 64 MiB", maxCache <= 64 * 1024 * 1024)
            val times = ui.onMain { delivered.toList() }
            return JSONObject().put("fixture", name).put("fixtureSha256", sha).put("run", run)
                .put("width", viewportWidth).put("height", viewportHeight)
                .put("initialZoom", initialZoom).put("refreshHz", refreshHz)
                .put("scenarios", scenarios).put("maxCacheBytes", maxCache)
                .put("memoryBefore", memoryBefore).put("memoryAfter", memory())
                .put("deliveredTiles", times.size)
                .put("queueP95Ms", percentile(times.map { it.queueNanos }))
                .put("nativeP95Ms", percentile(times.map { it.nativeNanos }))
                .put("deliveryP95Ms", percentile(times.map { it.deliveryNanos }))
                .put(
                    "debuggable",
                    activity.applicationInfo.flags and
                        android.content.pm.ApplicationInfo.FLAG_DEBUGGABLE != 0
                )
        } finally {
            ui.onMain {
                if (initialized) {
                    view.onSharpnessDraw = null
                    view.setRenderingEnabled(false)
                    worker.close()
                }
                activity.finish()
            }
            val closeDeadline = SystemClock.uptimeMillis() + 5_000
            while ((File("/proc/self/fd").list()?.size ?: Int.MAX_VALUE) > fdBefore + 4 &&
                SystemClock.uptimeMillis() < closeDeadline
            ) {
                SystemClock.sleep(25)
            }
            assertTrue(
                "Probe descriptors did not return",
                (File("/proc/self/fd").list()?.size ?: Int.MAX_VALUE) <= fdBefore + 4
            )
        }
    }

    private fun drag(view: PdfCanvasView, forward: Boolean) {
        val down = SystemClock.uptimeMillis()
        val start = view.height * if (forward) 0.85f else 0.15f
        val end = view.height * if (forward) 0.15f else 0.85f
        fun event(action: Int, y: Float) {
            val event = MotionEvent.obtain(
                down,
                SystemClock.uptimeMillis(),
                action,
                view.width * 0.5f,
                y,
                0
            )
            ui.onMain { view.dispatchTouchEvent(event) }
            event.recycle()
        }
        event(MotionEvent.ACTION_DOWN, start)
        repeat(6) { index ->
            SystemClock.sleep(16)
            event(MotionEvent.ACTION_MOVE, start + (end - start) * (index + 1) / 6)
        }
        SystemClock.sleep(150)
        event(MotionEvent.ACTION_MOVE, end)
        event(MotionEvent.ACTION_UP, end)
    }

    private fun percentile(values: List<Long>): Double {
        if (values.isEmpty()) return 0.0
        val sorted = values.sorted()
        return sorted[(ceil(sorted.size * 0.95).toInt() - 1).coerceAtLeast(0)] / 1_000_000.0
    }

    private fun memory(): JSONObject {
        val info = Debug.MemoryInfo()
        Debug.getMemoryInfo(info)
        return JSONObject().put("pssKb", info.totalPss).put("nativePssKb", info.nativePss)
    }
}
